// Generates three original mechanical-key click samples. No recorded audio.
import { writeFileSync } from "node:fs";

const RATE = 48000;
const rng = (seed) => { let s = seed >>> 0; return () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296; };

function click(seed, dur, f1, f2, thump) {
  const rand = rng(seed);
  const n = Math.round(RATE * dur);
  const out = new Float32Array(n);
  let prevNoise = 0;
  for (let i = 0; i < n; i++) {
    const t = i / RATE;
    const noise = rand() * 2 - 1;
    const hp = noise - prevNoise * 0.85;
    prevNoise = noise;
    const strike = Math.exp(-t / 0.0022);
    const body = Math.exp(-t / 0.010);
    const low = Math.exp(-t / 0.016);
    const s =
      hp * strike * 0.55 +
      Math.sin(2 * Math.PI * f1 * t) * body * 0.26 +
      Math.sin(2 * Math.PI * f2 * t) * Math.exp(-t / 0.005) * 0.12 +
      Math.sin(2 * Math.PI * thump * t) * low * 0.20;
    out[i] = s;
  }
  const fade = Math.round(RATE * 0.004);
  for (let i = 0; i < fade; i++) out[n - 1 - i] *= i / fade;
  let peak = 0;
  for (const v of out) peak = Math.max(peak, Math.abs(v));
  const scale = 0.62 / (peak || 1);
  const pcm = Buffer.alloc(n * 2);
  for (let i = 0; i < n; i++) {
    const v = Math.max(-1, Math.min(1, out[i] * scale));
    pcm.writeInt16LE(Math.round(v * 32767), i * 2);
  }
  return pcm;
}

const specs = [
  [0x51a3, 0.040, 1850, 3280, 168],
  [0x9c11, 0.046, 2060, 3540, 152],
  [0x2e77, 0.043, 1740, 3010, 181],
];
const encoded = specs.map((s) => click(...s).toString("base64"));
const ts = `// Generated by scripts/generate-typing-samples.mjs.\n// Three original synthesized key clicks (48 kHz, mono, ~40 ms). No sampled audio.\nexport const TYPING_SAMPLE_RATE = ${RATE};\nexport const TYPING_PCM = [\n${encoded.map((e) => `  ${JSON.stringify(e)},`).join("\n")}\n] as const;\n`;
writeFileSync("src/app/typing-samples.ts", ts);
console.log("wrote src/app/typing-samples.ts", ts.length, "bytes");
